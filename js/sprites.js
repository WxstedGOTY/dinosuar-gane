  /**
   * The circular-arrow restart button.
   *
   * The modern sprite sheet carries a browser logo in this slot rather than the
   * arrow the classic game shows, so this one is generated: a ring of whole
   * cells with a bite out of the top right and an arrow head on the loose end.
   * Built cell by cell so it sits with the rest of the artwork instead of
   * being a smooth arc.
   * @param {number} size grid cells across
   * @return {!Array<string>}
   */
  function buildRestartGrid(size) {
    var centre = (size - 1) / 2;
    var outer = size / 2 - 1;
    var inner = outer - 4;
    var gapFrom = -Math.PI * 0.46;
    var gapTo = -Math.PI * 0.17;

    var cells = [];
    var x, y;
    for (y = 0; y < size; y++) {
      cells.push([]);
      for (x = 0; x < size; x++) {
        var dx = x - centre;
        var dy = y - centre;
        var dist = Math.sqrt(dx * dx + dy * dy);
        var angle = Math.atan2(dy, dx);
        cells[y].push(dist <= outer && dist >= inner &&
                      !(angle >= gapFrom && angle <= gapTo));
      }
    }

    // Arrow head capping the open end, pointing the way the ring turns.
    var mid = (outer + inner) / 2;
    var baseX = centre + Math.cos(gapFrom) * mid;
    var baseY = centre + Math.sin(gapFrom) * mid;
    var half = (outer - inner) / 2 + 1.2;
    var reach = 7.5;
    for (y = 0; y < size; y++) {
      for (x = 0; x < size; x++) {
        var ax = x - baseX;
        var ay = y - baseY;
        if (ax >= -0.7 && ax <= reach &&
            Math.abs(ay) <= half * (1 - ax / reach) + 0.4) {
          cells[y][x] = true;
        }
      }
    }

    var grid = [];
    for (y = 0; y < size; y++) {
      var row = '';
      for (x = 0; x < size; x++) {
        row += cells[y][x] ? '#' : '.';
      }
      grid.push(row);
    }
    return grid;
  }

  // ------------------------------------------------------------- Rasterising --

  /**
   * Turn a pixel grid into an offscreen canvas.
   * @param {!Array<string>} grid
   * @param {string} colour
   * @return {!HTMLCanvasElement}
   */
  function rasterise(grid, colour) {
    var cols = grid[0].length;
    var rows = grid.length;
    var canvas = document.createElement('canvas');
    canvas.width = cols;
    canvas.height = rows;

    var ctx = canvas.getContext('2d');
    ctx.fillStyle = colour;

    for (var y = 0; y < rows; y++) {
      var row = grid[y];
      var runStart = -1;
      // Batch horizontal runs into single fillRect calls.
      for (var x = 0; x <= cols; x++) {
        var solid = x < cols && row.charAt(x) === '#';
        if (solid && runStart === -1) {
          runStart = x;
        } else if (!solid && runStart !== -1) {
          ctx.fillRect(runStart, y, x - runStart, 1);
          runStart = -1;
        }
      }
    }
    return canvas;
  }

